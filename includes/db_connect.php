<?php
/*
 * ไฟล์สำหรับเชื่อมต่อฐานข้อมูล
 * เก็บไว้ที่เดียวเพื่อความสะดวกในการแก้ไขและนำไปใช้
 */

// กำหนดค่าการเชื่อมต่อ
$servername = "localhost";        // โดยทั่วไปคือ localhost
$username_db = "root";            // ชื่อผู้ใช้ฐานข้อมูล (ของ XAMPP มักจะเป็น root)
$password_db = "";                // รหัสผ่าน (ของ XAMPP มักจะเว้นว่างไว้)
$dbname = "health_app";         // ชื่อฐานข้อมูลที่เราสร้างไว้

// สร้างการเชื่อมต่อด้วย PHP Data Objects (PDO) หรือ MySQLi
// ในที่นี้จะใช้ MySQLi ซึ่งเข้ากับโค้ดเดิมของเรา
$conn = new mysqli($servername, $username_db, $password_db, $dbname);

// ตั้งค่า character set ของการเชื่อมต่อเป็น utf8mb4 เพื่อรองรับภาษาไทย
$conn->set_charset("utf8mb4");

// ตรวจสอบการเชื่อมต่อ
if ($conn->connect_error) {
  // หากเชื่อมต่อไม่สำเร็จ ให้หยุดการทำงานและแสดงข้อผิดพลาด
  die("การเชื่อมต่อฐานข้อมูลล้มเหลว: " . $conn->connect_error);
}

// ไม่ต้องใส่ $conn->close(); ในไฟล์นี้นะครับ
// เพราะไฟล์อื่นๆ ที่จะเรียกใช้ไฟล์นี้ ยังต้องใช้งานตัวแปร $conn อยู่
?>